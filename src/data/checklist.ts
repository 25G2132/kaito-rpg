/** docs/check-list.md の中身（開発用モードの一覧と同じ） */
export function checklistMarkdown(): string {
  const lines: string[] = [
    '# 確かめること（S26 で）',
    '',
    'まだスマホ（S26）で確かめていないものの一覧。ゲームの中では、URL に `?dev` を付けて開き、左下の「開発」→「確かめること」でも見られる（同じ中身）。',
    'ゲームの中では、「行く」で確かめる場所へ飛べ、「できた／おかしい」を押すと開発用の保存に残る。',
    '',
    `全部で ${CHECK_ITEMS.length} 項目。`,
    '',
  ];
  let n = 0;
  for (const g of CHECKLIST) {
    lines.push(`## ${g.name}`, '');
    for (const it of g.items) {
      n++;
      lines.push(`### ${n}. ${it.title}`, '');
      lines.push('**やり方**', '');
      it.how.forEach((h, i) => lines.push(`${i + 1}. ${h}`));
      lines.push('', `**こうなれば正しい**：${it.ok}`, '');
      if (it.goLabel) lines.push(`「行く」：${it.goLabel}`, '');
    }
  }
  return lines.join('\n');
}
